/* static */
status_t
MenuPrivate::CreateBitmaps()
{
	BRect smallRect(0.0f, 0.0f, 16.0f, 10.0f);

	try {
		sMenuItemShift = new BBitmap(BRect(0.0f, 0.0f, 23.0f, 10.0f), B_RGB32);
		sMenuItemControl = new BBitmap(BRect(0.0f, 0.0f, 21.0f, 10.0f),
			B_RGB32);
		sMenuItemOption = new BBitmap(smallRect, B_RGB32);
		sMenuItemAlt = new BBitmap(smallRect, B_RGB32);
		sMenuItemMenu = new BBitmap(BRect(0.0f, 0.0f, 22.0f, 10.0f), B_RGB32);
	} catch (...) {
		return B_NO_MEMORY;
	}

	sMenuItemShift->ImportBits(kShiftBits, sizeof(kShiftBits),
		24, 0, B_CMAP8);
	sMenuItemControl->ImportBits(kCtrlBits, sizeof(kCtrlBits),
		22, 0, B_CMAP8);
	sMenuItemOption->ImportBits(kOptBits, sizeof(kOptBits),
		17, 0, B_CMAP8);
	sMenuItemAlt->ImportBits(kAltBits, sizeof(kAltBits),
		17, 0, B_CMAP8);
	sMenuItemMenu->ImportBits(kMenuBits, sizeof(kMenuBits),
		23, 0, B_CMAP8);

	return B_OK;
}


/* static */
void
MenuPrivate::DeleteBitmaps()
{
	delete sMenuItemShift;
	sMenuItemShift = NULL;
	delete sMenuItemControl;
	sMenuItemControl = NULL;
	delete sMenuItemOption;
	sMenuItemOption = NULL;
	delete sMenuItemAlt;
	sMenuItemAlt = NULL;
	delete sMenuItemMenu;
	sMenuItemMenu = NULL;
}


/* static */
const BBitmap*
MenuPrivate::MenuItemShift()
{
	return sMenuItemShift;
}


/* static */
const BBitmap*
MenuPrivate::MenuItemControl()
{
	switch (current_modifier_key(B_LEFT_CONTROL_KEY, BMenu::sControlKey)) {
		case KEY_LEFTALT:
		case KEY_RIGHTALT:
			return sMenuItemAlt;
	}

	return sMenuItemControl;
}


/* static */
const BBitmap*
MenuPrivate::MenuItemOption()
{
	switch (current_modifier_key(B_LEFT_OPTION_KEY, BMenu::sOptionKey)) {
		case KEY_LEFTCTRL:
		case KEY_RIGHTCTRL:
			return sMenuItemControl;
	}

	return sMenuItemAlt;
}


/* static */
const BBitmap*
MenuPrivate::MenuItemCommand()
{
	switch (current_modifier_key(B_LEFT_COMMAND_KEY, BMenu::sCommandKey)) {
		case KEY_LEFTCTRL:
		case KEY_RIGHTCTRL:
			return sMenuItemControl;
	}

	return sMenuItemAlt;
}


/* static */
const char*
MenuPrivate::MenuItemCommandGlyph()
{
#ifdef __APPLE__
	return "\xE2\x8C\x98";	// Apple cloverleaf symbol
#else
	return NULL;
#endif
}


/* static */
const BBitmap*
MenuPrivate::MenuItemMenu()
{
	return sMenuItemMenu;
}


